function fallbackOptions(item){
  const base=personaFallback[item.persona]||personaFallback.P02;
  const rotate=(parseInt(item.id.replace(/\D/g,''),10)||0)%3;
  return [0,1,2].map(i=>{const row=base[(i+rotate)%3];return C(row[0],row[1],row[2]);});
}

function contextualOptions(item){return exact[item.id]||fallbackOptions(item);}

function shouldReply(item){
  if(item.rare||item.special||item.arc)return true;
  const n=[...item.id].reduce((sum,ch)=>sum+ch.charCodeAt(0),0);
  return n%3===0;
}

function characterReply(item,choiceIndex){
  const tones=replyTone[item.persona]||['「好，我知道了。」'];
  return tones[choiceIndex%tones.length];
}

function storyFor(item,choiceIndex){
  const event=storyEvents[item.id];
  if(!event)return null;
  return {title:event.title,beats:event.branches[choiceIndex]||event.branches[0]};
}

window.RED_FLAG_INTERACTIONS={contextualOptions,shouldReply,characterReply,storyFor};
